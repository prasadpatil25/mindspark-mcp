import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { assembleWidgetHTML } from '../../web/build-widget.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const html = assembleWidgetHTML();
const out = `// GENERATED by scripts/build-widget-html.mjs — do not edit directly.
// Re-run \`npm run build:widget\` after changing anything under ../../web/.
export const WIDGET_HTML = ${JSON.stringify(html)};
`;
writeFileSync(join(__dirname, '..', 'src', 'widget-html.generated.js'), out);
console.log('Wrote src/widget-html.generated.js (' + html.length + ' bytes)');
